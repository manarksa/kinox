CREATE TABLE Users(
 Id INT IDENTITY PRIMARY KEY,
 Name NVARCHAR(100),
 Email NVARCHAR(100),
 Password NVARCHAR(100));

CREATE TABLE Movies(
 Id INT IDENTITY PRIMARY KEY,
 Title NVARCHAR(150),
 Category NVARCHAR(30),
 Year INT,
 Story NVARCHAR(MAX),
 Cast NVARCHAR(300),
 Poster NVARCHAR(300));

 CREATE TABLE Watchlist(
 Id INT IDENTITY PRIMARY KEY,
 UserId INT,
 MovieId INT);